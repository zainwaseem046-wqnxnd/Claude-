import fs from "node:fs";
import fsp from "node:fs/promises";
import path from "node:path";
import crypto from "node:crypto";
import multer from "multer";
import { config } from "../config.js";
import { badRequest } from "./errors.js";

export const MAX_PHOTO_BYTES = 8 * 1024 * 1024;
export const MAX_PHOTOS_PER_KIND = 8;

fs.mkdirSync(config.uploadDir, { recursive: true });

/** Uploads are buffered in memory (size-capped) so content can be checked before anything is written to disk. */
export const imageUpload = multer({
  storage: multer.memoryStorage(),
  limits: { fileSize: MAX_PHOTO_BYTES, files: 1, fields: 5 },
});

/** Detects real image type from magic bytes. Only JPEG and PNG are accepted (both embed in PDFs). */
export function sniffImage(buf: Buffer): "image/jpeg" | "image/png" | null {
  if (buf.length > 3 && buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) return "image/jpeg";
  if (buf.length > 8 && buf.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))) return "image/png";
  return null;
}

export async function saveImage(buf: Buffer | undefined): Promise<{ fileName: string; mime: string; size: number }> {
  if (!buf || buf.length === 0) throw badRequest("No image was uploaded");
  const mime = sniffImage(buf);
  if (!mime) throw badRequest("Only JPEG or PNG images are allowed");
  const fileName = crypto.randomUUID() + (mime === "image/png" ? ".png" : ".jpg");
  await fsp.writeFile(filePath(fileName), buf, { mode: 0o600 });
  return { fileName, mime, size: buf.length };
}

/** Resolves a stored file name safely inside the upload dir (names are generated by us, but never trust). */
export function filePath(fileName: string) {
  const base = path.basename(fileName);
  if (!/^[0-9a-f-]{36}\.(jpg|png)$/.test(base)) throw badRequest("Invalid file");
  return path.join(config.uploadDir, base);
}

export async function deleteFile(fileName: string | null | undefined) {
  if (!fileName) return;
  await fsp.rm(filePath(fileName), { force: true });
}
